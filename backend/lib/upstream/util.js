import fs from "node:fs";
import net from "node:net";
import { isVariableHost } from "../nginx-locations.js";

const RESOLVERS_CONF = "/etc/nginx/conf.d/include/resolvers.conf";
const RESOLV_CONF = "/etc/resolv.conf";
const DOCKER_EMBEDDED_DNS = "127.0.0.11";

// Characters that would break out of the nginx config, plus anything that can never be part of a host
// biome-ignore lint/suspicious/noControlCharactersInRegex: control characters are exactly what we reject
const FORBIDDEN_HOST_CHARS = /[\s;{}'"`$\\#\x00-\x1f\x7f]/;
const HOSTNAME_PATTERN =
	/^(?=.{1,253}\.?$)[A-Za-z0-9_](?:[A-Za-z0-9_-]{0,62})(?:\.[A-Za-z0-9_](?:[A-Za-z0-9_-]{0,62}))*\.?$/;

// isVariableHost(host): a forward host (without any path) with an nginx variable, eg. `$backend` set in the
// advanced config or `app-$stage`. nginx resolves it per request, it can't be checked from here. The rule of the
// location renderer, which writes such a host literally.

/**
 * Splits a forward host the way the location renderer does: "host/some/path" -> host + "/some/path".
 * Surrounding whitespace is trimmed.
 *
 * @param   {string} value
 * @returns {{host: string, path: string}}
 */
const splitHostPath = (value) => {
	const raw = `${value ?? ""}`.trim();
	const idx = raw.indexOf("/");
	if (idx === -1) {
		return { host: raw, path: "" };
	}
	return { host: raw.slice(0, idx), path: raw.slice(idx) };
};

/**
 * Removes the brackets of an IPv6 literal ("[::1]" -> "::1")
 *
 * @param   {string} host
 * @returns {string}
 */
const unbracket = (host) => {
	if (host.startsWith("[") && host.endsWith("]")) {
		return host.slice(1, -1);
	}
	return host;
};

/**
 * @param   {string} host  Host without any path
 * @returns {boolean}
 */
const isValidHost = (host) => {
	if (typeof host !== "string" || host === "" || host.length > 253) {
		return false;
	}
	if (FORBIDDEN_HOST_CHARS.test(host)) {
		return false;
	}
	if (net.isIP(unbracket(host))) {
		return true;
	}
	return HOSTNAME_PATTERN.test(host);
};

/**
 * Turns a Docker embedded DNS PTR answer into a container name.
 * Docker answers "<container_name>.<network_name>." for containers on a user-defined network.
 * Returns the possible host names in order of preference (spec: drop the last label; as a
 * fallback, the first label, for network names containing dots) together with the network.
 *
 * @param   {string} ptrName
 * @returns {Array<{host: string, network: string}>}
 */
const parsePtrName = (ptrName) => {
	if (typeof ptrName !== "string") {
		return [];
	}
	const name = ptrName.trim().replace(/\.+$/, "");
	const labels = name.split(".").filter((label) => label !== "");
	if (labels.length < 2) {
		return [];
	}
	const out = [{ host: labels.slice(0, -1).join("."), network: labels[labels.length - 1] }];
	if (labels.length > 2) {
		out.push({ host: labels[0], network: labels.slice(1).join(".") });
	}
	return out.filter((item) => isValidHost(item.host));
};

/**
 * @param   {string} ip  IPv4 address
 * @returns {number}     unsigned 32-bit int
 */
const ipv4ToInt = (ip) => {
	const parts = ip.split(".").map((p) => Number.parseInt(p, 10));
	return ((parts[0] << 24) | (parts[1] << 16) | (parts[2] << 8) | parts[3]) >>> 0;
};

/**
 * @param   {number} value
 * @returns {string}
 */
const intToIpv4 = (value) => [(value >>> 24) & 255, (value >>> 16) & 255, (value >>> 8) & 255, value & 255].join(".");

/**
 * @param   {string} cidr  ie "172.18.0.5/16"
 * @returns {{network: number, first: number, last: number, prefix: number}|null}
 */
const parseIpv4Cidr = (cidr) => {
	const match = /^(\d{1,3}(?:\.\d{1,3}){3})\/(\d{1,2})$/.exec(`${cidr ?? ""}`);
	if (!match || !net.isIPv4(match[1])) {
		return null;
	}
	const prefix = Number.parseInt(match[2], 10);
	if (prefix < 0 || prefix > 32) {
		return null;
	}
	const mask = prefix === 0 ? 0 : (0xffffffff << (32 - prefix)) >>> 0;
	const network = (ipv4ToInt(match[1]) & mask) >>> 0;
	const broadcast = (network | (~mask >>> 0)) >>> 0;
	if (prefix >= 31) {
		return { network, first: network, last: broadcast, prefix };
	}
	return { network, first: network + 1, last: broadcast - 1, prefix };
};

/**
 * Parses the nginx resolver directive generated by prepare/40-dynamic.sh:
 *   resolver 127.0.0.11 [::1] ipv6=off valid=10s;
 *
 * @param   {string} content
 * @returns {{servers: string[], ipv6: boolean}|null}  null when no resolver is configured
 */
const parseResolversConf = (content) => {
	if (typeof content !== "string") {
		return null;
	}
	const servers = [];
	let ipv6 = true;
	for (const rawLine of content.split("\n")) {
		const line = rawLine.replace(/#.*$/, "").trim();
		const match = /^resolver\s+([^;]*);?/.exec(line);
		if (!match) {
			continue;
		}
		for (const token of match[1].split(/\s+/)) {
			if (token === "") {
				continue;
			}
			if (token.includes("=")) {
				if (/^ipv6=off$/i.test(token)) {
					ipv6 = false;
				}
				continue;
			}
			const server = normaliseServer(token);
			if (server) {
				servers.push(server);
			}
		}
	}
	return servers.length ? { servers, ipv6 } : null;
};

/**
 * Converts an nginx resolver address into a form accepted by dns.Resolver#setServers
 *
 * @param   {string} token  "1.2.3.4", "1.2.3.4:53", "[::1]", "[::1]:53", "::1"
 * @returns {string|null}
 */
const normaliseServer = (token) => {
	if (net.isIP(token)) {
		return token;
	}
	const v6 = /^\[([^\]]+)\](?::(\d+))?$/.exec(token);
	if (v6 && net.isIPv6(v6[1])) {
		return v6[2] ? `[${v6[1]}]:${v6[2]}` : v6[1];
	}
	const v4 = /^([\d.]+):(\d+)$/.exec(token);
	if (v4 && net.isIPv4(v4[1])) {
		return token;
	}
	return null;
};

/**
 * @param   {string} [file]
 * @returns {{servers: string[], ipv6: boolean}|null}
 */
const readNginxResolvers = (file = RESOLVERS_CONF) => {
	try {
		return parseResolversConf(fs.readFileSync(file, "utf8"));
	} catch (_) {
		return null;
	}
};

/**
 * @param   {string} content  /etc/resolv.conf contents
 * @returns {string[]}
 */
const parseResolvConfNameservers = (content) => {
	const out = [];
	for (const line of `${content ?? ""}`.split("\n")) {
		const match = /^\s*nameserver\s+(\S+)/.exec(line);
		if (match) {
			out.push(match[1].replace(/%.*$/, ""));
		}
	}
	return out;
};

/**
 * @param   {string} [file]
 * @returns {string[]}
 */
const readResolvConfNameservers = (file = RESOLV_CONF) => {
	try {
		return parseResolvConfNameservers(fs.readFileSync(file, "utf8"));
	} catch (_) {
		return [];
	}
};

/**
 * Parses /proc/net/route and returns the IPv4 gateways (little-endian hex on x86/arm).
 *
 * @param   {string} content
 * @returns {string[]}
 */
const parseProcNetRouteGateways = (content) => {
	const out = new Set();
	const lines = `${content ?? ""}`.split("\n").slice(1);
	for (const line of lines) {
		const cols = line.trim().split(/\s+/);
		if (cols.length < 3 || !/^[0-9A-Fa-f]{8}$/.test(cols[2]) || cols[2] === "00000000") {
			continue;
		}
		const hex = cols[2];
		const bytes = [hex.slice(6, 8), hex.slice(4, 6), hex.slice(2, 4), hex.slice(0, 2)].map((b) =>
			Number.parseInt(b, 16),
		);
		out.add(bytes.join("."));
	}
	return [...out];
};

/**
 * Minimal promise concurrency limiter
 *
 * @param   {number} max
 * @returns {function(function(): Promise): Promise}
 */
const createLimiter = (max) => {
	let active = 0;
	const queue = [];
	const next = () => {
		if (active >= max || !queue.length) {
			return;
		}
		active++;
		const { fn, resolve, reject } = queue.shift();
		Promise.resolve()
			.then(fn)
			.then(resolve, reject)
			.finally(() => {
				active--;
				next();
			});
	};
	return (fn) =>
		new Promise((resolve, reject) => {
			queue.push({ fn, resolve, reject });
			next();
		});
};

/**
 * Rejects/resolves with `onTimeout()` if the promise hasn't settled in `ms`.
 * The underlying operation is not cancelled.
 *
 * @param   {Promise}  promise
 * @param   {number}   ms
 * @param   {function} onTimeout
 * @returns {Promise}
 */
const withTimeout = (promise, ms, onTimeout) => {
	let timer;
	const timeout = new Promise((resolve, reject) => {
		timer = setTimeout(() => {
			try {
				resolve(onTimeout());
			} catch (err) {
				reject(err);
			}
		}, ms);
	});
	return Promise.race([promise, timeout]).finally(() => clearTimeout(timer));
};

