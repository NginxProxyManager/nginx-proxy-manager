/**
 * Decides how a custom location's upstream host is rendered:
 *
 * - "dynamic": `proxy_pass` uses a variable, nginx resolves the name per request through
 *   its `resolver`. An unknown host only breaks that location (502) and never fails `nginx -t`.
 * - "static": `proxy_pass` uses the literal host name (the pre-2.14 behaviour). nginx resolves it
 *   with the system resolver when the config is loaded, which honours /etc/hosts and search domains.
 *
 * This module has no database imports so it can be unit tested.
 */

import dns from "node:dns";
import fs from "node:fs";
import net from "node:net";

const RESOLVERS_FILE = "/etc/nginx/conf.d/include/resolvers.conf";
const HOSTS_FILE = "/etc/hosts";
// Together at most ~2s per host name: the resolver query, a short guard for its settle, then the system lookup
const RESOLVER_TIMEOUT_MS = 800;
const RESOLVER_GUARD_MS = 200;
const LOOKUP_TIMEOUT_MS = 800;

const toBool = (v, fallback) => {
	if (typeof v === "undefined" || v === null || `${v}`.trim() === "") {
		return fallback;
	}
	return /^(1|true|yes|on)$/i.test(`${v}`.trim());
};

/**
 * @returns {boolean}
 */
const isDynamicDnsEnabled = (env = process.env) => toBool(env.NPM_LOCATION_DYNAMIC_DNS, true);

/**
 * Parses the nginx resolvers.conf generated by prepare/40-dynamic.sh, e.g.
 *   resolver 127.0.0.11 [::1] ipv6=off valid=10s;
 *
 * @param   {String} text
 * @returns {{servers: String[], ipv6: boolean}|null}  null when no resolver is configured
 */
const parseResolversConf = (text) => {
	const servers = [];
	let ipv6 = true;
	const content = `${text || ""}`.replace(/#.*$/gm, "");
	const regex = /(?:^|[\s;])resolver\s+([^;]+);/g;
	let match = regex.exec(content);
	while (match) {
		for (const token of match[1].trim().split(/\s+/)) {
			if (token === "ipv6=off") {
				ipv6 = false;
			} else if (token.indexOf("=") === -1 && token !== "") {
				servers.push(token);
			}
		}
		match = regex.exec(content);
	}
	return servers.length ? { servers, ipv6 } : null;
};

/**
 * Converts an nginx resolver address to one accepted by dns.Resolver#setServers
 *
 * @param   {String} server
 * @returns {String}
 */
const toNodeDnsServer = (server) => {
	if (server.startsWith("[")) {
		// [::1] or [::1]:53
		return server.endsWith("]") ? server.slice(1, -1) : server;
	}
	return server;
};

/**
 * @param   {String} text  contents of /etc/hosts
 * @returns {Set<String>}  lower cased host names
 */
const parseHostsFile = (text) => {
	const names = new Set();
	for (const rawLine of `${text || ""}`.split("\n")) {
		const line = rawLine.replace(/#.*$/, "").trim();
		if (!line) {
			continue;
		}
		const parts = line.split(/\s+/);
		parts.shift();
		for (const name of parts) {
			names.add(name.toLowerCase());
		}
	}
	return names;
};

const stripBrackets = (host) => (host.startsWith("[") && host.endsWith("]") ? host.slice(1, -1) : host);

/**
 * @param   {String} host
 * @returns {boolean}
 */
const isIpLiteral = (host) => net.isIP(stripBrackets(`${host || ""}`)) !== 0;

const readFileOrNull = (file) => {
	try {
		return fs.readFileSync(file, { encoding: "utf8" });
	} catch {
		return null;
	}
};

const withTimeout = (promise, ms) =>
	new Promise((resolve) => {
		const timer = setTimeout(() => resolve({ ok: false, timeout: true }), ms);
		promise.then(
			(value) => {
				clearTimeout(timer);
				resolve(value);
			},
			() => {
				clearTimeout(timer);
				resolve({ ok: false });
			},
		);
	});

/**
 * Creates a function that computes the location mode of a host name. Results are cached for the lifetime
 * of the returned function, which is meant to be created once per configure() call.
 *
 * @param   {Object}   [options]
 * @param   {Object}   [options.env]
 * @param   {String}   [options.resolversFile]
 * @param   {String}   [options.hostsFile]
 * @param   {Function} [options.resolveViaResolver]  async (host, resolverConfig) => boolean, for tests
 * @param   {Function} [options.resolveViaSystem]    async (host) => boolean, for tests
 * @returns {Function} async (host) => {mode: "dynamic"|"static", status: "ok"|"unresolved", reason: String}
 */
const createModeResolver = (options = {}) => {
	const env = options.env || process.env;
	const dynamicEnabled = isDynamicDnsEnabled(env);
	const resolverDisabled = toBool(env.DISABLE_RESOLVER, false);
	const resolverConfig = resolverDisabled
		? null
		: parseResolversConf(readFileOrNull(options.resolversFile || RESOLVERS_FILE));
	let hostNames = null;
	const cache = new Map();

	const resolveViaResolver =
		options.resolveViaResolver ||
		(async (host, config) => {
			const resolver = new dns.promises.Resolver({ timeout: RESOLVER_TIMEOUT_MS, tries: 1 });
			resolver.setServers(config.servers.map(toNodeDnsServer));
			const lookups = [resolver.resolve4(host)];
			if (config.ipv6) {
				lookups.push(resolver.resolve6(host));
			}
			const results = await Promise.allSettled(lookups);
			return results.some((r) => r.status === "fulfilled" && r.value.length > 0);
		});

	const resolveViaSystem =
		options.resolveViaSystem ||
		(async (host) => {
			const addresses = await dns.promises.lookup(host, { all: true });
			return addresses.length > 0;
		});

	const compute = async (rawHost) => {
		const host = `${rawHost || ""}`.trim().toLowerCase();

		if (!dynamicEnabled) {
			return { mode: "static", status: "ok", reason: "dynamic_dns_disabled" };
		}
		if (!resolverConfig) {
			return { mode: "static", status: "ok", reason: "no_resolver" };
		}
		if (isIpLiteral(host)) {
			return { mode: "static", status: "ok", reason: "ip_literal" };
		}
		if (hostNames === null) {
			hostNames = parseHostsFile(readFileOrNull(options.hostsFile || HOSTS_FILE));
		}
		if (hostNames.has(host)) {
			return { mode: "static", status: "ok", reason: "etc_hosts" };
		}

		const viaResolver = await withTimeout(
			resolveViaResolver(host, resolverConfig).then((ok) => ({ ok })),
			RESOLVER_TIMEOUT_MS + RESOLVER_GUARD_MS,
		);
		if (viaResolver.ok) {
			return { mode: "dynamic", status: "ok", reason: "resolver" };
		}

		const viaSystem = await withTimeout(
			resolveViaSystem(host).then((ok) => ({ ok })),
			LOOKUP_TIMEOUT_MS,
		);
		if (viaSystem.ok) {
			// Only resolvable through search domains or similar, keep today's literal behaviour
			return { mode: "static", status: "ok", reason: "system_only" };
		}

		return { mode: "dynamic", status: "unresolved", reason: "not_found" };
	};

	const modeFor = (rawHost) => {
		const key = `${rawHost || ""}`.trim().toLowerCase();
		if (!cache.has(key)) {
			cache.set(key, compute(key));
		}
		return cache.get(key);
	};

	modeFor.hasResolver = !!resolverConfig;
	modeFor.dynamicEnabled = dynamicEnabled;
	return modeFor;
};

export {
	createModeResolver,
	isDynamicDnsEnabled,
	isIpLiteral,
	parseHostsFile,
	parseResolversConf,
	stripBrackets,
	toBool,
	toNodeDnsServer,
};
